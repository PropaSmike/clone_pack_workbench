def sqb_tone_owners(path):
    """Which vanilla stages own the tones an sqb references, most first."""
    import collections
    with open(path, "rb") as handle:
        blob = handle.read()
    seen = set()
    for index in range(len(blob) - 8):
        value = int.from_bytes(blob[index:index + 5], "little")
        if 8 <= (value >> 32) <= 60:
            seen.add(value)
    owners = collections.Counter()
    for value in seen:
        stage = STAGE_TONE_OWNER.get(value)
        if stage:
            owners[stage] += 1
    return owners.most_common()
